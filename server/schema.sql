CREATE TABLE IF NOT EXISTS creations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  prompt TEXT NOT NULL,
  content TEXT NOT NULL,
  type TEXT NOT NULL,
  publish BOOLEAN NOT NULL DEFAULT FALSE,
  likes TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS creations_user_created_at_idx
  ON creations (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS creations_published_created_at_idx
  ON creations (created_at DESC)
  WHERE publish = TRUE;
